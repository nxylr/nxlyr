#!/usr/bin/env python3
"""Probe Deepgram multi-language streaming on global/EU hosts with key terms."""

import argparse
import asyncio
import json
import os
import sys
import time
import unicodedata
import wave
from pathlib import Path
from urllib.parse import urlencode

import requests
import websockets
from deepgram.core.query_encoder import encode_query
from pipecat.transcriptions.language import Language

AGENT_DIR = Path(__file__).resolve().parents[1] / "agent"
if str(AGENT_DIR) not in sys.path:
    sys.path.insert(0, str(AGENT_DIR))

from commitments import PROJECT_SLUG
from stt_keyterms import STTCheckingDeepgramService, build_stt_settings


HOSTS = {
    "global": "api.deepgram.com",
    "eu": "api.eu.deepgram.com",
}
DEFAULT_KB_PATH = AGENT_DIR / "prompt_scripts" / "kb_meridian_heights.json"


def script_share(text: str) -> tuple[str, int, int]:
    deva = sum(
        unicodedata.category(char).startswith("L") and "\u0900" <= char <= "\u097f"
        for char in text
    )
    latin = sum(
        unicodedata.category(char).startswith("L")
        and (("A" <= char <= "Z") or ("a" <= char <= "z"))
        for char in text
    )
    total = deva + latin
    if total == 0:
        return "none", deva, latin
    share = deva / total
    script = "deva" if share >= 0.8 else "latin" if share <= 0.2 else "mixed"
    return script, deva, latin


def language_results(codes: list[str]) -> str:
    results = []
    for code in codes:
        try:
            Language(code)
        except (TypeError, ValueError):
            results.append(f"{code}:rejected")
        else:
            results.append(f"{code}:accepted")
    return ",".join(results) or "none"


def read_audio(path: Path) -> bytes:
    with wave.open(str(path), "rb") as wav:
        if wav.getnchannels() != 1 or wav.getframerate() != 8000:
            raise ValueError("audio must be an 8 kHz mono WAV")
        if wav.getsampwidth() != 2:
            raise ValueError("audio must use 16-bit samples")
        if wav.getcomptype() != "NONE":
            raise ValueError("audio must be uncompressed PCM WAV")
        return wav.readframes(wav.getnframes())


def load_live_project_kb() -> dict:
    """Load the live project config without reading a dotenv file."""
    supabase_url = os.getenv("SUPABASE_URL")
    supabase_key = os.getenv("SUPABASE_SERVICE_ROLE_KEY")
    if not supabase_url or not supabase_key:
        raise RuntimeError(
            "SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required for live key terms"
        )
    response = requests.get(
        f"{supabase_url.rstrip('/')}/rest/v1/projects",
        headers={
            "apikey": supabase_key,
            "Authorization": f"Bearer {supabase_key}",
            "Accept": "application/json",
        },
        params={
            "select": "config,tenants!inner(slug)",
            "tenants.slug": f"eq.{PROJECT_SLUG}",
            "limit": "1",
        },
        timeout=(2.0, 5.0),
    )
    if response.status_code != 200:
        raise RuntimeError(f"live project KB request failed: HTTP {response.status_code}")
    rows = response.json()
    if not isinstance(rows, list) or not rows or not isinstance(rows[0].get("config"), dict):
        raise RuntimeError("live project KB response did not contain a config")
    return rows[0]["config"]


def load_kb_file(path: Path) -> dict:
    project_kb = json.loads(path.read_text())
    if not isinstance(project_kb, dict):
        raise ValueError("KB file must contain a JSON object")
    return project_kb


def build_connect_params(
    project_kb: dict,
    *,
    api_key: str,
    region: str,
    keyterms: bool,
    numerals: bool,
) -> dict:
    """Return the SDK connection parameters generated by the production service."""
    service_args = {
        "api_key": api_key,
        "sample_rate": 8000,
        "settings": build_stt_settings(
            project_kb,
            language_mode="hinglish",
            keyterms=keyterms,
            numerals=numerals,
        ),
        "region": region,
        "hinglish": True,
    }
    if region == "eu":
        service_args["base_url"] = "api.eu.deepgram.com"
    service = STTCheckingDeepgramService(**service_args)
    # Pipecat resolves this field from StartFrame immediately before connecting.
    service._sample_rate = 8000
    return service._build_connect_kwargs()


async def probe_row(
    *,
    api_key: str,
    audio: bytes,
    project_kb: dict,
    region: str,
    keyterms: bool,
    numerals: bool,
) -> None:
    params = build_connect_params(
        project_kb,
        api_key=api_key,
        region=region,
        keyterms=keyterms,
        numerals=numerals,
    )
    query = encode_query(params)
    url = f"wss://{HOSTS[region]}/v1/listen?{urlencode(query)}"
    label = (
        f"region={region} keyterms={'on' if keyterms else 'off'} "
        f"numerals={'on' if numerals else 'off'}"
    )
    started_at = time.monotonic()
    connected = False
    try:
        async with websockets.connect(
            url,
            additional_headers={"Authorization": f"Token {api_key}"},
            open_timeout=10,
            close_timeout=5,
        ) as socket:
            connected = True
            parameter_names = ",".join(sorted(params))
            print(f"{label} connected=yes parameter_names={parameter_names}")
            for offset in range(0, len(audio), 3200):
                await socket.send(audio[offset : offset + 3200])
                await asyncio.sleep(0.2)
            await socket.send(json.dumps({"type": "Finalize"}))
            try:
                while True:
                    raw = await asyncio.wait_for(socket.recv(), timeout=15)
                    message = json.loads(raw)
                    if message.get("type") != "Results" or not message.get("is_final"):
                        continue
                    alternatives = message.get("channel", {}).get("alternatives", [])
                    if not alternatives:
                        continue
                    transcript = alternatives[0].get("transcript", "")
                    if not transcript:
                        continue
                    languages = alternatives[0].get("languages") or []
                    script, deva, latin = script_share(transcript)
                    elapsed_ms = int((time.monotonic() - started_at) * 1000)
                    print(
                        f"{label} transcript_received=yes final_ms={elapsed_ms} "
                        f"script={script} deva_letters={deva} latin_letters={latin} "
                        f"languages={languages or ['none']} "
                        f"pipecat={language_results(languages)}"
                    )
                    print(f"{label} transcript={transcript}")
                    await socket.send(json.dumps({"type": "CloseStream"}))
                    return
            except asyncio.TimeoutError:
                print(f"{label} transcript_received=no script=none error=TimeoutError")
                await socket.send(json.dumps({"type": "CloseStream"}))
    except Exception as error:
        response = getattr(error, "response", None)
        status = getattr(response, "status_code", None)
        close_code = getattr(error, "code", None)
        print(
            f"{label} connected={'yes' if connected else 'no'} "
            f"transcript_received=no script=none error={type(error).__name__} "
            f"http_status={status or 'none'} close_code={close_code or 'none'}"
        )


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "wav",
        type=Path,
        help=(
            "3-5 second Hindi/Hinglish recording, 8 kHz mono 16-bit PCM WAV; "
            "if creating one, save it as ~/hinglish_8k.wav"
        ),
    )
    parser.add_argument("--kb-file", type=Path, default=DEFAULT_KB_PATH)
    parser.add_argument(
        "--live-kb",
        action="store_true",
        help="load the live project KB (requires SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY)",
    )
    return parser


async def main() -> None:
    args = build_arg_parser().parse_args()
    api_key = os.getenv("DEEPGRAM_API_KEY")
    if not api_key:
        raise RuntimeError("DEEPGRAM_API_KEY is required")
    audio = read_audio(args.wav)
    project_kb = (
        await asyncio.to_thread(load_live_project_kb)
        if args.live_kb
        else load_kb_file(args.kb_file)
    )
    for region in ("global", "eu"):
        for keyterms in (False, True):
            for numerals in (False, True):
                await probe_row(
                    api_key=api_key,
                    audio=audio,
                    project_kb=project_kb,
                    region=region,
                    keyterms=keyterms,
                    numerals=numerals,
                )


if __name__ == "__main__":
    asyncio.run(main())
